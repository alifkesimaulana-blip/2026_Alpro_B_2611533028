# Buat file dengan nama perbandingan_2611533028.py
# Nama variabel ditambah 4 digit nim terakhir contoh: angka1_3028
# Progaram ini menggunakan fungsi input()
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# Program operator perbandingan dalam Python

angka1_3028 = int(input("input angka-1:"))
angka2_3028 = int(input("input angka-2:"))

# Lebih besar dari
hasil_3028 = angka1_3028 > angka2_3028
print("\nOperator lebih besar dari")
print("angka1_3028 > angka2_3028 =", hasil_3028)

# Lebih kecil dari
hasil_3028 = angka1_3028 < angka2_3028
print("\nOperator lebih kecil dari")
print("angka1_3028 < angka2_3028 =", hasil_3028)

# Lebih kecil dari atau sama dengan
hasil_3028 = angka1_3028 <= angka2_3028
print("\nOperator lebih kecil atau sama dengan")
print("angka1_3028 <= angka2_3028 =", hasil_3028)

# Sama dengan
hasil_3028 = angka1_3028 = angka2_3028
print("\nOperator sama dengan")
print("angka1_3028 = angka2_3028 =", hasil_3028)

# Tidak sama dengan 
hasil_3028 = angka1_3028 = angka2_3028
print("\nOperator tidak sama dengan")
print("angka1_3028 != angka2_3028 =", hasil_3028)

# Tambahan: perbandingan berantai dalam Python
hasil_3028 = 0 < angka1_3028 < 100
print("\nPerbandingan berantai")
print("0 < angka1_3028 < 100 =", hasil_3028)

hasil_3028 = 0 < angka2_3028 < 100
